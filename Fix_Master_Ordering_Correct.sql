(
	@SRAID				VARCHAR(24)		=	'%',
	@KEYWORD			VARCHAR(MAX)	=	'%',
	@COMPANYID			VARCHAR(24)		=	'',
	@DEPTID				VARCHAR(24)		=	''
)
RETURNS TABLE
AS
RETURN
(
	SELECT TOP 2147483647
		COALESCE(SRAID				,	'')		AS		SRAID
	   ,COALESCE(SABHASADNAME		,	'')		AS		SABHASADNAME
	   ,COALESCE(CONTACTNUMBER		,	'')		AS		CONTACTNUMBER
	   ,COALESCE(CONVERT(VARCHAR(16),BIRTHDATE,	106)	,	'')	AS			BIRTHDATE
	   ,COALESCE(AGE				,	'')		AS		AGE
	   ,COALESCE(VILLAGENAME		,	'')		AS		VILLAGENAME
	   ,COALESCE(PINCODE			,	'')		AS		PINCODE
	   ,COALESCE(CITY				,	'')		AS		CITY
	   ,COALESCE(STATE				,	'')		AS		STATE
	   ,COALESCE(PRIMARYBUSINESS	,	'')		AS		PRIMARYBUSINESS
