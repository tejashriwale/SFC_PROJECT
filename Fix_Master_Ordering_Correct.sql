							OR PSUBCATEGORY LIKE '%' + @KEYWORD + '%'
							OR PHSN			LIKE '%' + @KEYWORD + '%'
							OR PRODUCTID    LIKE '%' + @KEYWORD + '%'
				)
	ORDER BY P.SYSDT DESC, P.PAID DESC
)
