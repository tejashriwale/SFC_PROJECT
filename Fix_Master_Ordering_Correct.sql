	   ,COALESCE(TOTALLAND			,	'')		AS		TOTALLAND
	   ,COALESCE(IRRIGATEDLAND		,	'')		AS		IRRIGATEDLAND
	   ,COALESCE(NONIRRIGATEDLAND	,	'')		AS		NONIRRIGATEDLAND
	   ,COALESCE(NOMINALNAME		,	'')		AS		NOMINALNAME
	   ,COALESCE(NOMINALAGE			,	'')		AS		NOMINALAGE
	   ,COALESCE(NOMINALRELATION	,	'')		AS		NOMINALRELATION
	   ,COALESCE(PHOTOS            	,	'')		AS		PHOTOS
	   ,COALESCE(FORM				,	'')		AS		FORM
	   ,COALESCE(C.ImplicationTitle	,	'')		AS		ImplicationTitle
	   ,COALESCE(S.SSTATENAME		,	'')		AS		SSTATENAME
	   ,COALESCE(S.SDISTRICT		,	'')		AS		SDISTRICT
	   ,COALESCE(CONVERT(VARCHAR(16),REGDATE,	106)	,	'')	AS			REGDATE
	   ,COALESCE(REGNO				,	'')		AS		REGNO
	FROM	tblSabhasadMaster  A
			LEFT JOIN	ST_Implication C  ON C.ISDELETED = 0 AND  C.ImplicationGroup = 'RELATIONS' AND  C.ImplicationValue = A.NOMINALRELATION
			LEFT JOIN	tblStateCodeMasters S  ON S.ISDELETED = 0  AND  S.SAID = A.STATE
			LEFT JOIN	tblStateCodeMasters D  ON D.ISDELETED = 0  AND  D.SAID = A.CITY
	WHERE	A.ISDELETED	=	0
		AND	A.COMPANYID	=	@COMPANYID
		AND	A.DEPTID		=	@DEPTID
		AND	A.SRAID	LIKE	@SRAID
			AND	(
							SABHASADNAME		LIKE    '%'		+   @KEYWORD	+	'%'
					    OR  CONTACTNUMBER		LIKE	'%'		+	@KEYWORD	+	'%'
						OR	VILLAGENAME			LIKE	'%'		+	@KEYWORD	+	'%'
			)
	ORDER BY A.REGDATE DESC, A.SRAID DESC
)
