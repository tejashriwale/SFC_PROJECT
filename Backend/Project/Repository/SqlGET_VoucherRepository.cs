                dbContext.Database.OpenConnection();

                using (var reader = await command.ExecuteReaderAsync())
                {
                    while (await reader.ReadAsync())
                    {
                        list.Add(new GET_Voucher
                        {
                            VoucherAID = reader.GetInt32("VoucherAID"),
